/** The {names} a text uses, in order of first appearance. */
export const placeholders = (text: string): string[] => [...new Set([...text.matchAll(/\{([a-zA-Z0-9]+)\}/g)].map(m => m[1] ?? ''))]

/** How the owner is addressed: config.address when set, else the fallback of the language. */
export const addressFor = (lang: Language, configured: string | undefined): string => configured?.trim() || ADDRESS_FALLBACK[lang]

/** Fills a text; a missing value is an error (fail loudly rather than show a raw {name} to the owner). */
export function fill(lang: Language, key: string, vars: Readonly<Record<string, string | number>>): string {
  const text = TEXTS[lang][key]
  if (text === undefined) throw new Error(`flow text "${key}" is missing in ${lang}`)
  return text.replace(/\{([a-zA-Z0-9]+)\}/g, (_, name: string) => {
    const v = vars[name]
    if (v === undefined) throw new Error(`flow text "${key}" needs {${name}}`)
    return String(v)
  })
}
